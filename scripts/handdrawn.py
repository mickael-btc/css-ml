def grid(rows):
    return np.array([[c == "#" for c in r] for r in rows], np.uint8)


def dataset():
    """Every digit, plus copies shifted by one cell and shrunk into a corner."""
    X, y = [], []
    for label, rows in DIGITS:
        g = grid(rows)
        for dx, dy in [(0, 0), (1, 0), (-1, 0), (0, 1), (0, -1)]:
            if (dx == 1 and g[:, -1].any()) or (dx == -1 and g[:, 0].any()) or \
               (dy == 1 and g[-1].any()) or (dy == -1 and g[0].any()):
                continue  # would wrap around the edge
            X.append(np.roll(np.roll(g, dy, 0), dx, 1).ravel())
            y.append(label)
        idx = np.arange(6) * 8 // 6
        small = np.zeros((8, 8), np.uint8)
        small[:6, :6] = g[np.ix_(idx, idx)]
        X.append(small.ravel())
        y.append(label)
    return np.array(X), np.array(y)
